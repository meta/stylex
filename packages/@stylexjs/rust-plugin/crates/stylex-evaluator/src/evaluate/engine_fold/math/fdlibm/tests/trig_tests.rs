#[test]
fn sin_gives_the_bits_of_node() {
  for &(x, expected) in SIN_ROWS {
    assert_same_bits(sin(x), expected, x);
  }
}

#[test]
fn cos_gives_the_bits_of_node() {
  for &(x, expected) in COS_ROWS {
    assert_same_bits(cos(x), expected, x);
  }
}

#[test]
fn tan_gives_the_bits_of_node() {
  for &(x, expected) in TAN_ROWS {
    assert_same_bits(tan(x), expected, x);
  }
}

#[test]
fn sin_and_tan_keep_the_sign_of_zero() {
  for x in [0.0, -0.0] {
    assert_same_bits(sin(x), x, x);
    assert_same_bits(tan(x), x, x);
  }
}

#[test]
fn cos_of_zero_is_one() {
  for x in [0.0, -0.0] {
    assert_same_bits(cos(x), 1.0, x);
  }
}

#[test]
fn infinities_and_nan_give_nan() {
  for x in [f64::INFINITY, f64::NEG_INFINITY, f64::NAN] {
    assert_same_bits(sin(x), f64::NAN, x);
    assert_same_bits(cos(x), f64::NAN, x);
    assert_same_bits(tan(x), f64::NAN, x);
  }
}

#[test]
fn tan_gives_the_bits_of_node_on_x64_where_arm64_differs() {
  // Node on arm64 gives -1.6287782256068988 here.
  assert_same_bits(tan(1e22), -1.628778225606899, 1e22);
  assert_same_bits(tan(-1e22), 1.628778225606899, -1e22);
}
